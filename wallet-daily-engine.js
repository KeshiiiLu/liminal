/*
  Liminal · reality-time finance engine

  Calendar may hold future plans. This engine is the only automatic path that
  turns those plans into posted Wallet transactions, and it never processes a
  production date later than the current Asia/Shanghai date.
*/

(function () {
  "use strict";

  const finance = window.LiminalFinance;
  const time = window.LiminalTime;
  const runtime = window.LiminalWalletRuntimeData;
  const CALENDAR_STORAGE_KEY = "liminal_calendar_preview_v1";
  const ENGINE_VERSION = 1;
  const CLEANUP_VERSION = 1;
  const SAFE_AUTOMATIC_SOURCE_TYPES = new Set([
    "household_shopping",
    "food_calendar",
    "calendar_meal",
    "calendar_expense",
    "system_generated_daily_expense",
    "meal_auto_expense",
    "calendar_shopping"
  ]);

  if (!finance || !time || !runtime) {
    console.warn("Wallet Daily Engine：依赖尚未加载。\n");
    return;
  }

  function roundMoney(value) {
    return Math.round((Number(value) + Number.EPSILON) * 100) / 100;
  }

  function hashString(text) {
    let hash = 2166136261;
    for (let index = 0; index < String(text).length; index += 1) {
      hash ^= String(text).charCodeAt(index);
      hash = Math.imul(hash, 16777619);
    }
    return hash >>> 0;
  }

  function stableAmount(seed, range) {
    const ratio = (hashString(seed) % 100000) / 99999;
    return roundMoney(Number(range.min) + ratio * (Number(range.max) - Number(range.min)));
  }

  function ensureEngineState() {
    const state = finance.getState();
    if (!state.automation || typeof state.automation !== "object" || Array.isArray(state.automation)) {
      state.automation = {};
    }
    if (!state.automation.walletDaily || typeof state.automation.walletDaily !== "object" || Array.isArray(state.automation.walletDaily)) {
      state.automation.walletDaily = {};
    }
    const daily = state.automation.walletDaily;
    daily.version = ENGINE_VERSION;
    daily.timeZone = time.TIME_ZONE;
    if (!daily.processedDates || typeof daily.processedDates !== "object" || Array.isArray(daily.processedDates)) {
      daily.processedDates = {};
    }
    if (!state.payroll || typeof state.payroll !== "object" || Array.isArray(state.payroll)) {
      state.payroll = {};
    }
    if (!state.payroll.postedPeriods || typeof state.payroll.postedPeriods !== "object" || Array.isArray(state.payroll.postedPeriods)) {
      state.payroll.postedPeriods = {};
    }
    if (!state.payroll.calculatedPeriods || typeof state.payroll.calculatedPeriods !== "object" || Array.isArray(state.payroll.calculatedPeriods)) {
      state.payroll.calculatedPeriods = {};
    }
    if (!Array.isArray(state.earningsLedger)) state.earningsLedger = [];
    return { state, daily };
  }

  function loadCalendarData() {
    const raw = localStorage.getItem(CALENDAR_STORAGE_KEY);
    if (!raw) return null;
    try {
      const parsed = JSON.parse(raw);
      return parsed && typeof parsed === "object" && !Array.isArray(parsed) ? parsed : null;
    } catch (error) {
      console.error("Wallet Daily Engine：Calendar 数据无法解析，未覆盖原数据。", error);
      return null;
    }
  }

  function saveCalendarData(calendarData) {
    if (!calendarData) return;
    localStorage.setItem(CALENDAR_STORAGE_KEY, JSON.stringify(calendarData));
  }

  function findSourceTransaction(sourceType, sourceId, externalRef = "") {
    const transactions = finance.getState().transactions || [];
    return transactions.find((item) => (
      (externalRef && item.externalRef === externalRef) ||
      (item.sourceType === sourceType && item.sourceId === sourceId)
    )) || null;
  }

  function postTransaction(input) {
    const existing = findSourceTransaction(input.sourceType, input.sourceId, input.externalRef);
    return finance.upsertTransaction({
      ...(existing || {}),
      ...input,
      transactionId: existing?.transactionId || input.transactionId || finance.createId("transaction"),
      originWorld: "sub",
      world: "secondary",
      status: "posted",
      realizationStatus: "realized",
      autoGenerated: true,
      generatedBy: "wallet_daily_engine",
      processedDate: input.date,
      createdAt: existing?.createdAt || new Date().toISOString()
    });
  }

  function isSafelyRecognizedFutureAutomatic(transaction, todayKey) {
    if (!transaction || transaction.date <= todayKey || transaction.originWorld !== "sub") return false;
    const recognizedSource = SAFE_AUTOMATIC_SOURCE_TYPES.has(transaction.sourceType) ||
      ["calendar_household_shopping", "calendar_meal", "system_daily_expense"].includes(transaction.source);
    const explicitAutomatic = transaction.autoGenerated === true ||
      transaction.generatedBy === "wallet_daily_engine" ||
      transaction.calendarGenerated === true ||
      Boolean(transaction.shoppingPurchaseId);
    return recognizedSource && (explicitAutomatic || ["household_shopping", "food_calendar"].includes(transaction.sourceType));
  }

  function clearCalendarTransactionReference(calendarData, transaction) {
    if (!calendarData) return;
    if (transaction.sourceType === "household_shopping") {
      const record = calendarData.householdShopping?.days?.[transaction.date];
      if (record && (!record.walletTransactionId || record.walletTransactionId === transaction.transactionId)) {
        record.walletTransactionId = null;
        record.walletSyncStatus = "planned";
        record.status = "planned";
        if (record.walletDraft) record.walletDraft.status = "planned";
      }
    }
    if (transaction.sourceType === "food_calendar") {
      const record = calendarData.foodCalendar?.[transaction.date];
      if (record && (!record.walletTransactionId || record.walletTransactionId === transaction.transactionId)) {
        record.walletTransactionId = null;
        record.walletSyncStatus = "planned";
        record.status = "planned";
        if (record.walletDraft) record.walletDraft.status = "planned";
      }
    }
  }

  function cleanupFutureAutomaticTransactions(todayKey, calendarData, daily) {
    const candidates = (finance.getState().transactions || [])
      .filter((item) => isSafelyRecognizedFutureAutomatic(item, todayKey));
    const removed = [];
    candidates.forEach((transaction) => {
      if (finance.deleteTransaction(transaction.transactionId)) {
        clearCalendarTransactionReference(calendarData, transaction);
        removed.push({
          transactionId: transaction.transactionId,
          date: transaction.date,
          sourceType: transaction.sourceType || transaction.source || ""
        });
      }
    });
    const previousRemoved = Array.isArray(daily.futureCleanup?.removed)
      ? daily.futureCleanup.removed
      : [];
    const combined = [...previousRemoved, ...removed].filter((item, index, values) => (
      values.findIndex((candidate) => candidate.transactionId === item.transactionId) === index
    ));
    daily.futureCleanup = {
      version: CLEANUP_VERSION,
      checkedAt: new Date().toISOString(),
      throughDate: todayKey,
      removed: combined,
      lastRemoved: removed
    };
    return removed;
  }

  function rowIdentity(row, dateKey, index) {
    return String(
      row.simulationId || row.luzhenSimulationId || row.householdShoppingId || row.id ||
      `${dateKey}:row:${index}`
    );
  }

  function rowDetails(row) {
    return {
      title: row.title || row.luzhen || row.keshi || "日程",
      time: row.startTime || row.luzhenTime || row.keshiTime || "12:00",
      eventType: row.eventType || row.luzhenEventType || row.keshiEventType || "schedule",
      mealSource: row.mealSource || row.luzhenMealSource || row.keshiMealSource || "",
      location: row.location || row.luzhenLocation || row.keshiLocation || "",
      tags: Array.isArray(row.tags)
        ? row.tags
        : Array.isArray(row.luzhenTags)
          ? row.luzhenTags
          : []
    };
  }

  function realizeMeals(calendarData, dateKey) {
    const rows = Array.isArray(calendarData?.schedule?.[dateKey]) ? calendarData.schedule[dateKey] : [];
    const posted = [];
    rows.forEach((row, index) => {
      const details = rowDetails(row);
      if (details.eventType !== "meal" || row.source !== "generated" && row.luzhenSource !== "generated") return;
      const expense = runtime.mealExpenses[details.mealSource];
      if (!expense) {
        row.status = "realized";
        return;
      }
      const sourceId = `meal:${dateKey}:${rowIdentity(row, dateKey, index)}`;
      const location = window.LiminalHouseholdShopping?.getLocationAtTime
        ? window.LiminalHouseholdShopping.getLocationAtTime(calendarData, dateKey, details.time)
        : details.location || "shanghai";
      const amount = stableAmount(sourceId, expense);
      const reimbursementDate = typeof row.expenseContext?.reimbursementDate === "string"
        ? row.expenseContext.reimbursementDate
        : "";
      const transaction = postTransaction({
        externalRef: `calendar_meal:${sourceId}`,
        source: "calendar_meal",
        sourceType: "calendar_meal",
        sourceId,
        sourceDate: dateKey,
        scheduleId: rowIdentity(row, dateKey, index),
        type: "expense",
        amount,
        currency: "CNY",
        title: details.title,
        category: expense.category,
        subcategory: details.mealSource,
        note: location && location !== "shanghai" ? `发生地：${location}` : "",
        fromAccountId: "cmb_daily",
        toAccountId: "",
        ledgerOwner: row.owner === "both" ? "family" : "luzhen",
        location,
        reimbursable: row.expenseContext?.reimbursable === true || expense.reimbursable === true,
        reimbursementDate,
        date: dateKey,
        timeOfDay: details.time,
        occurredAt: `${dateKey}T${details.time}:00+08:00`
      });
      row.status = "realized";
      row.walletTransactionId = transaction.transactionId;
      posted.push(transaction.transactionId);
    });
    return posted;
  }

  function realizeExplicitCalendarExpenses(calendarData, dateKey) {
    const rows = Array.isArray(calendarData?.schedule?.[dateKey]) ? calendarData.schedule[dateKey] : [];
    const posted = [];
    rows.forEach((row, index) => {
      const details = rowDetails(row);
      const context = row.expenseContext;
      if (details.eventType === "meal" || !context || context.immediateExpense !== true) return;
      const amount = Number(context.amount);
      if (!Number.isFinite(amount) || amount <= 0) return;
      const sourceId = `calendar-expense:${dateKey}:${rowIdentity(row, dateKey, index)}`;
      const location = window.LiminalHouseholdShopping?.getLocationAtTime
        ? window.LiminalHouseholdShopping.getLocationAtTime(calendarData, dateKey, details.time)
        : details.location || "shanghai";
      const transaction = postTransaction({
        externalRef: `calendar_expense:${sourceId}`,
        source: "calendar_expense",
        sourceType: "calendar_expense",
        sourceId,
        sourceDate: dateKey,
        scheduleId: rowIdentity(row, dateKey, index),
        type: "expense",
        amount,
        currency: context.currency || "CNY",
        title: context.title || details.title,
        category: context.category || "其他",
        subcategory: context.subcategory || "",
        note: context.note || "",
        fromAccountId: context.accountId || context.resolvedAccountId || "cmb_daily",
        toAccountId: "",
        ledgerOwner: context.owner || "luzhen",
        location,
        reimbursable: context.reimbursable === true,
        reimbursementDate: context.reimbursementDate || "",
        date: dateKey,
        timeOfDay: details.time,
        occurredAt: `${dateKey}T${details.time}:00+08:00`
      });
      row.status = "realized";
      row.walletTransactionId = transaction.transactionId;
      posted.push(transaction.transactionId);
    });
    return posted;
  }

  function workTypeFor(details) {
    const title = details.title;
    if (details.tags.includes("consulting") || /咨询|接诊/.test(title)) return "consultation";
    if (details.tags.includes("supervision") || /督导/.test(title)) return "supervision";
    if (details.tags.includes("lecture") || /讲座|培训|大学活动/.test(title)) return "lecture";
    if (/项目|MDT/.test(title)) return "project";
    return "professional_work";
  }

  function accrueWork(calendarData, dateKey, state) {
    const rows = Array.isArray(calendarData?.schedule?.[dateKey]) ? calendarData.schedule[dateKey] : [];
    const existingIds = new Set(state.earningsLedger.map((item) => item.id));
    const inserted = [];
    rows.forEach((row, index) => {
      const details = rowDetails(row);
      const isWork = details.tags.includes("work") || /咨询|接诊|督导|讲座|培训|项目|MDT|病例|备课|会议/.test(details.title);
      if (!isWork || row.status === "cancelled") return;
      const sourceScheduleId = rowIdentity(row, dateKey, index);
      const id = `earning:${dateKey}:${sourceScheduleId}`;
      if (existingIds.has(id)) return;
      const workType = workTypeFor(details);
      const earnedMonth = time.monthKey(dateKey);
      const delayed = ["lecture", "project"].includes(workType);
      const settlementMonth = delayed
        ? time.addMonths(earnedMonth, runtime.payroll.projectSettlementDelayMonths)
        : earnedMonth;
      const entry = {
        id,
        date: dateKey,
        workType,
        title: details.title,
        amount: null,
        amountPending: true,
        earnedMonth,
        settlementMonth,
        status: "accrued",
        sourceScheduleId,
        originWorld: "sub",
        createdAt: new Date().toISOString()
      };
      state.earningsLedger.push(entry);
      existingIds.add(id);
      inserted.push(id);
    });
    return inserted;
  }

  function payDateForPeriod(period) {
    return `${time.addMonths(period, 1)}-${String(runtime.payroll.payDay).padStart(2, "0")}`;
  }

  function grossForPeriod(period) {
    const [year, month] = period.split("-").map(Number);
    const values = runtime.payroll.salaryGrossByWorkYear[year];
    return Array.isArray(values) ? Number(values[month - 1]) || 0 : 0;
  }

  function postPayrollDue(processingDate, state) {
    const posted = [];
    let period = runtime.payroll.runtimeStartPeriod;
    const latestPeriod = time.addMonths(time.monthKey(processingDate), -1);
    while (period <= latestPeriod) {
      const payDate = payDateForPeriod(period);
      const sourceId = `payroll:${period}`;
      const existing = findSourceTransaction("payroll", sourceId, sourceId);
      if (existing) {
        state.payroll.postedPeriods[period] = {
          payrollPeriod: period,
          payDate: existing.date,
          postedTransactionId: existing.transactionId,
          status: "posted"
        };
      } else if (payDate <= processingDate && !state.payroll.postedPeriods[period]?.postedTransactionId) {
        const gross = grossForPeriod(period);
        const [year] = period.split("-").map(Number);
        const netRate = Number(runtime.payroll.salaryNetRates[year]);
        if (gross > 0 && Number.isFinite(netRate)) {
          const accruals = state.earningsLedger.filter((item) => (
            item.status === "accrued" && item.settlementMonth <= period
          ));
          const amount = roundMoney(gross * netRate);
          state.payroll.calculatedPeriods[period] = {
            payrollPeriod: period,
            grossEstimate: gross,
            netEstimate: amount,
            calculatedAt: new Date().toISOString(),
            status: "calculated",
            accrualIds: accruals.map((item) => item.id)
          };
          const transaction = postTransaction({
            externalRef: sourceId,
            source: "payroll_engine",
            sourceType: "payroll",
            sourceId,
            payrollPeriod: period,
            payDate,
            type: "income",
            amount,
            currency: "CNY",
            title: "曼朗心理｜工资及绩效",
            category: "工资",
            subcategory: "税后工资及绩效",
            note: "固定工资、当期已结算绩效及进入结算窗口的项目收入。",
            fromAccountId: "",
            toAccountId: runtime.payroll.accountId,
            ledgerOwner: "luzhen",
            employer: runtime.payroll.employer,
            grossEstimate: gross,
            withholdingEstimate: roundMoney(gross - amount),
            accrualIds: accruals.map((item) => item.id),
            date: payDate,
            timeOfDay: runtime.payroll.payTime,
            occurredAt: `${payDate}T${runtime.payroll.payTime}:00+08:00`
          });
          accruals.forEach((entry) => {
            entry.status = "settled";
            entry.postedTransactionId = transaction.transactionId;
            entry.postedAt = new Date().toISOString();
          });
          state.payroll.postedPeriods[period] = {
            payrollPeriod: period,
            payDate,
            postedTransactionId: transaction.transactionId,
            status: "posted",
            postedAt: new Date().toISOString()
          };
          posted.push(transaction.transactionId);
        }
      }
      period = time.addMonths(period, 1);
    }
    return posted;
  }

  function postReimbursementsDue(processingDate) {
    const posted = [];
    const expenses = (finance.getState().transactions || []).filter((item) => (
      item.originWorld === "sub" && item.reimbursable === true &&
      time.isDateKey(item.reimbursementDate) && item.reimbursementDate <= processingDate
    ));
    expenses.forEach((expense) => {
      const sourceId = `reimbursement:${expense.transactionId}`;
      const transaction = postTransaction({
        externalRef: sourceId,
        source: "calendar_reimbursement",
        sourceType: "calendar_reimbursement",
        sourceId,
        reimbursementFor: expense.transactionId,
        type: "income",
        amount: expense.amount,
        currency: expense.currency || "CNY",
        title: "差旅报销",
        category: "退款",
        subcategory: "差旅报销",
        note: expense.title,
        fromAccountId: "",
        toAccountId: expense.fromAccountId || "cmb_daily",
        ledgerOwner: expense.ledgerOwner || "luzhen",
        date: expense.reimbursementDate,
        timeOfDay: "10:00",
        occurredAt: `${expense.reimbursementDate}T10:00:00+08:00`
      });
      expense.reimbursementStatus = "posted";
      expense.reimbursementTransactionId = transaction.transactionId;
      posted.push(transaction.transactionId);
    });
    return posted;
  }

  function realizeManualPlans(processingDate) {
    const realized = [];
    (finance.getState().transactions || []).forEach((transaction) => {
      if (
        transaction.source === "manual" &&
        transaction.status === "planned" &&
        transaction.date <= processingDate
      ) {
        transaction.status = "posted";
        transaction.realizationStatus = "realized";
        transaction.realizedAt = transaction.realizedAt || new Date().toISOString();
        realized.push(transaction.transactionId);
      }
    });
    return realized;
  }

  function markCalendarDateRealized(calendarData, dateKey) {
    const rows = Array.isArray(calendarData?.schedule?.[dateKey]) ? calendarData.schedule[dateKey] : [];
    rows.forEach((row) => {
      if (row.status === "planned" && row.source !== "manual") row.status = "realized";
    });
  }

  function processDate(calendarData, dateKey, state) {
    const result = {
      date: dateKey,
      shopping: null,
      foodCalendar: null,
      mealTransactions: [],
      calendarExpenseTransactions: [],
      earnings: [],
      reimbursements: [],
      payroll: [],
      manualPlans: []
    };
    if (calendarData && window.LiminalHouseholdShopping) {
      result.shopping = window.LiminalHouseholdShopping.realizeForDate?.(calendarData, dateKey, dateKey) || null;
      result.foodCalendar = window.LiminalHouseholdShopping.realizeFoodCalendarForDate?.(calendarData, dateKey, dateKey) || null;
      result.mealTransactions = realizeMeals(calendarData, dateKey);
      result.calendarExpenseTransactions = realizeExplicitCalendarExpenses(calendarData, dateKey);
      result.earnings = accrueWork(calendarData, dateKey, state);
      markCalendarDateRealized(calendarData, dateKey);
    }
    result.reimbursements = postReimbursementsDue(dateKey);
    result.payroll = postPayrollDue(dateKey, state);
    result.manualPlans = realizeManualPlans(dateKey);
    return result;
  }

  function run(options = {}) {
    const realToday = time.todayKey();
    const requested = time.isDateKey(options.today) ? options.today : realToday;
    const targetDate = requested < realToday ? requested : realToday;
    const calendarData = options.calendarData || loadCalendarData();
    const persistCalendar = typeof options.saveCalendar === "function"
      ? options.saveCalendar
      : () => saveCalendarData(calendarData);
    const { state, daily } = ensureEngineState();
    const cleanupRemoved = cleanupFutureAutomaticTransactions(targetDate, calendarData, daily);

    let startDate;
    if (time.isDateKey(daily.lastProcessedDate)) {
      startDate = time.addDays(daily.lastProcessedDate, 1);
    } else {
      const baselineStart = time.addDays(finance.definitions.baselineDate, 1);
      startDate = baselineStart <= targetDate ? baselineStart : targetDate;
    }

    const processed = [];
    if (startDate <= targetDate) {
      for (const dateKey of time.enumerateDateKeys(startDate, targetDate)) {
        if (daily.processedDates[dateKey]?.completed === true) {
          daily.lastProcessedDate = dateKey;
          continue;
        }
        try {
          const result = processDate(calendarData, dateKey, state);
          if (calendarData) persistCalendar();
          daily.processedDates[dateKey] = {
            completed: true,
            completedAt: new Date().toISOString(),
            result
          };
          daily.lastProcessedDate = dateKey;
          finance.save();
          processed.push(dateKey);
        } catch (error) {
          daily.lastError = {
            date: dateKey,
            message: String(error?.message || error),
            occurredAt: new Date().toISOString()
          };
          finance.save();
          console.error(`Wallet Daily Engine：${dateKey} 处理失败，日期未标记完成。`, error);
          break;
        }
      }
    }

    if (calendarData && cleanupRemoved.length) persistCalendar();
    daily.lastRunAt = new Date().toISOString();
    daily.lastRunTarget = targetDate;
    finance.save();
    const result = {
      timeZone: time.TIME_ZONE,
      realToday,
      targetDate,
      lastProcessedDate: daily.lastProcessedDate || null,
      processed,
      cleanupRemoved
    };
    window.LiminalWalletDailyLastResult = result;
    return result;
  }

  window.LiminalWalletDailyEngine = {
    ENGINE_VERSION,
    CALENDAR_STORAGE_KEY,
    run,
    cleanupFutureAutomaticTransactions: (todayKey, calendarData = loadCalendarData()) => {
      const { daily } = ensureEngineState();
      const removed = cleanupFutureAutomaticTransactions(todayKey, calendarData, daily);
      if (calendarData) saveCalendarData(calendarData);
      finance.save();
      return removed;
    }
  };
})();
